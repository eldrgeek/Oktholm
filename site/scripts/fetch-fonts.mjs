// Downloads the brand's Google Fonts (latin subset, woff2) into public/fonts and writes public/fonts/fonts.css.
// Self-hosting: no third-party font requests in production, and previews render offline.
//   node scripts/fetch-fonts.mjs [brand]
import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const brandId = process.argv[2] || process.env.BRAND || 'oktholm';
const brand = (await import(pathToFileURL(path.join(root, 'brands', brandId, 'index.js')).href)).default;
const href = brand.site?.fontsHref;
if (!href) throw new Error('brand.site.fontsHref is not set');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const css = execFileSync('curl', ['-sSL', '-A', UA, href], { encoding: 'utf8' });
const outDir = path.join(root, 'public', 'fonts');
mkdirSync(outDir, { recursive: true });
// Google returns one @font-face per unicode subset, each preceded by a /* subset */ comment. Keep latin only.
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)].filter((m) => m[1] === 'latin');
let out = '/* Self-hosted fonts (latin subset). Generated by scripts/fetch-fonts.mjs — do not edit. */\n';
for (const [, , block] of blocks) {
  const family = /font-family:\s*'([^']+)'/.exec(block)[1];
  const weight = /font-weight:\s*(\d+)/.exec(block)?.[1] || '400';
  const style = /font-style:\s*(\w+)/.exec(block)?.[1] || 'normal';
  const url = /url\(([^)]+)\)/.exec(block)[1];
  const file = `${family.replace(/\s+/g, '')}-${weight}${style === 'italic' ? 'i' : ''}.woff2`;
  execFileSync('curl', ['-sSL', '-A', UA, '-o', path.join(outDir, file), url]);
  out += block.replace(/url\([^)]+\)/, `url(./${file})`) + '\n';
  console.log('font', file);
}
writeFileSync(path.join(outDir, 'fonts.css'), out);
console.log(`wrote public/fonts/fonts.css (${blocks.length} faces)`);
